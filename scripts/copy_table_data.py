#!/usr/bin/env python
"""把正式库 FT_OWEN 的一张表拷到测试库 fc_admin。

正式库只读。一次只处理一张表，表名由参数指定。
目标表已有数据时直接停；要先清空目标表再导入，加 --replace。

用法（在 Hold-Backend 根目录）:
  python scripts/copy_table_data.py ROLE
  python scripts/copy_table_data.py FT_HOLD_RECORD --limit 100
  python scripts/copy_table_data.py FT_HOLD_RECORD --replace
  python scripts/copy_table_data.py TEST_BINCODE --limit 1000 --batch-size 5000

有外键时先导被引用的表。例如 ROLE 先于 USERS，TEST_WAFER 先于 TEST_BINCODE，
FT_HOLD_RECORD 先于 CIRCULATION_HISTORY。
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parents[1]
if str(_ROOT) not in sys.path:
    sys.path.insert(0, str(_ROOT))

import oracledb

from app.config import DB_PROFILES

TABLES = (
    'CIRCULATION_HISTORY',
    'CP_CIRCULATION_HISTORY',
    'CP_HOLD_RECORD',
    'DEFECT_CODE',
    'DEFECT_CODE_SYNC_LOG',
    'FT_CLIENT_ERROR',
    'FT_ENG_NOTES',
    'FT_HOLD_INFO',
    'FT_HOLD_PREDICT',
    'FT_HOLD_RECORD',
    'FT_WLT_TESTLOG',
    'HISTORY_DISPOSITION',
    'HOLD_INFO',
    'PRODUCT_INFO',
    'ROLE',
    'SOFTWARE_INFO',
    'TEST_BINCODE',
    'TEST_WAFER',
    'USERS',
    'WLT_HOLD_INFO',
)
_ALLOWED = frozenset(TABLES)
_NEXTVAL_RE = re.compile(r'"?([A-Z][A-Z0-9_$#]*)"?\s*\.\s*"?NEXTVAL"?', re.I)


def quote_name(name: str) -> str:
    if not re.fullmatch(r'[A-Z][A-Z0-9_$#]+', name):
        raise SystemExit(f'非法对象名: {name}')
    return f'"{name}"'


def connect(profile: dict):
    dsn = f"{profile['host']}:{profile['port']}/{profile['service_name']}"
    return oracledb.connect(user=profile['user'], password=profile['password'], dsn=dsn)


def columns_of(cur, table: str) -> list[str]:
    cur.execute(
        """
        SELECT column_name
        FROM user_tab_cols
        WHERE table_name = :name
          AND virtual_column = 'NO'
          AND hidden_column = 'NO'
        ORDER BY column_id
        """,
        {'name': table},
    )
    return [row[0] for row in cur.fetchall()]


def count_rows(cur, table: str) -> int:
    cur.execute(f'SELECT COUNT(*) FROM {quote_name(table)}')
    return int(cur.fetchone()[0])


def identity_columns(cur, table: str) -> list[tuple[str, str]]:
    cur.execute(
        """
        SELECT column_name, generation_type
        FROM user_tab_identity_cols
        WHERE table_name = :name
        ORDER BY column_name
        """,
        {'name': table},
    )
    return [(name, generation) for name, generation in cur.fetchall()]


def sequence_defaults(cur, table: str) -> list[tuple[str, str]]:
    cur.arraysize = 1
    cur.execute(
        """
        SELECT column_name, data_default
        FROM user_tab_columns
        WHERE table_name = :name
          AND data_default IS NOT NULL
        ORDER BY column_id
        """,
        {'name': table},
    )
    found = []
    for column_name, data_default in cur.fetchall():
        text = data_default.read() if hasattr(data_default, 'read') else str(data_default or '')
        match = _NEXTVAL_RE.search(text)
        if not match:
            continue
        sequence_name = match.group(1).upper()
        if sequence_name.startswith('ISEQ$$'):
            continue
        found.append((column_name, sequence_name))
    return found


def disable_triggers(cur, table: str) -> None:
    cur.execute(f'ALTER TABLE {quote_name(table)} DISABLE ALL TRIGGERS')


def enable_triggers(cur, table: str) -> None:
    cur.execute(f'ALTER TABLE {quote_name(table)} ENABLE ALL TRIGGERS')


def restore_identity_mode(cur, table: str, identities: list[tuple[str, str]]) -> None:
    """没写入数据时，只把 GENERATED ALWAYS 改回去，不动起始值。"""
    for column_name, generation in identities:
        if generation != 'ALWAYS':
            continue
        cur.execute(
            f'ALTER TABLE {quote_name(table)} MODIFY {quote_name(column_name)} '
            'GENERATED ALWAYS AS IDENTITY'
        )


def relax_identity(cur, table: str, identities: list[tuple[str, str]]) -> None:
    for column_name, generation in identities:
        if generation != 'ALWAYS':
            continue
        cur.execute(
            f'ALTER TABLE {quote_name(table)} MODIFY {quote_name(column_name)} '
            'GENERATED BY DEFAULT AS IDENTITY'
        )


def restart_identity(cur, table: str, identities: list[tuple[str, str]]) -> None:
    for column_name, generation in identities:
        cur.execute(
            f'SELECT NVL(MAX({quote_name(column_name)}), 0) + 1 FROM {quote_name(table)}'
        )
        nxt = int(cur.fetchone()[0])
        generated = 'ALWAYS' if generation == 'ALWAYS' else 'BY DEFAULT'
        cur.execute(
            f'ALTER TABLE {quote_name(table)} MODIFY {quote_name(column_name)} '
            f'GENERATED {generated} AS IDENTITY (START WITH {nxt})'
        )
        print(f'身份列 {column_name} 下一值 {nxt}')


def restart_sequence(cur, sequence_name: str, start_with: int) -> None:
    cur.execute(
        """
        SELECT min_value
        FROM user_sequences
        WHERE sequence_name = :name
        """,
        {'name': sequence_name},
    )
    row = cur.fetchone()
    if row is None:
        print(f'目标库没有序列 {sequence_name}，跳过')
        return
    start_with = max(start_with, int(row[0]))
    cur.execute(
        f'ALTER SEQUENCE {quote_name(sequence_name)} RESTART START WITH {start_with}'
    )
    print(f'序列 {sequence_name} 下一值 {start_with}')


def restart_sequences(cur, table: str, pairs: list[tuple[str, str]]) -> None:
    for column_name, sequence_name in pairs:
        cur.execute(
            f'SELECT NVL(MAX({quote_name(column_name)}), 0) + 1 FROM {quote_name(table)}'
        )
        restart_sequence(cur, sequence_name, int(cur.fetchone()[0]))


def clear_target(cur, table: str) -> None:
    try:
        cur.execute(f'TRUNCATE TABLE {quote_name(table)}')
    except oracledb.Error as exc:
        if 'ORA-02266' not in str(exc):
            raise
        raise SystemExit(
            f'{table} 被其它表的外键引用，不能清空。先清空子表，或不要加 --replace。'
        ) from exc


def copy_rows(
    source_cur,
    target_cur,
    table: str,
    columns: list[str],
    batch_size: int,
    progress: list[int],
    limit: int | None,
) -> int:
    listed = ', '.join(quote_name(name) for name in columns)
    placeholders = ', '.join(f':{index}' for index in range(1, len(columns) + 1))
    select_sql = f'SELECT {listed} FROM {quote_name(table)}'
    if limit is not None:
        if 'ID' in columns:
            select_sql += f' ORDER BY {quote_name("ID")} DESC'
        select_sql += f' FETCH FIRST {int(limit)} ROWS ONLY'
    insert_sql = (
        f'INSERT INTO {quote_name(table)} ({listed}) VALUES ({placeholders})'
    )
    source_cur.arraysize = batch_size
    source_cur.execute(select_sql)
    copied = 0
    while True:
        rows = source_cur.fetchmany(batch_size)
        if not rows:
            break
        target_cur.executemany(insert_sql, rows)
        target_cur.connection.commit()
        copied += len(rows)
        progress[0] = copied
        print(f'已写入 {copied} 行')
    return copied


def parse_args():
    parser = argparse.ArgumentParser(description='从正式库拷一张表到测试库')
    parser.add_argument('table', help='表名，例如 FT_HOLD_RECORD')
    parser.add_argument(
        '--replace',
        action='store_true',
        help='导入前清空目标表。目标表已有数据时必须加这个参数',
    )
    parser.add_argument(
        '--limit',
        type=int,
        default=None,
        help='最多导入多少行。有 ID 列时按 ID 从大到小取，省略则导入整表',
    )
    parser.add_argument(
        '--batch-size',
        type=int,
        default=2000,
        help='每批提交的行数，默认 2000',
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    table = args.table.strip().upper()
    if table not in _ALLOWED:
        print(f'不能导入 {table}。可用表名:', file=sys.stderr)
        for name in TABLES:
            print(f'  {name}', file=sys.stderr)
        return 1
    if args.batch_size < 1:
        print('--batch-size 必须大于 0', file=sys.stderr)
        return 1
    if args.limit is not None and args.limit < 1:
        print('--limit 必须大于 0', file=sys.stderr)
        return 1

    source_profile = DB_PROFILES['release']
    target_profile = DB_PROFILES['test']
    if source_profile['host'] == target_profile['host']:
        print('源库和目标库是同一台，已中止', file=sys.stderr)
        return 1

    print(
        f"源: {source_profile['user']} @ {source_profile['host']}/"
        f"{source_profile['service_name']} 只读"
    )
    print(
        f"目标: {target_profile['user']} @ {target_profile['host']}/"
        f"{target_profile['service_name']}"
    )
    print(f'表: {table}')

    oracledb.defaults.fetch_lobs = False
    source = connect(source_profile)
    try:
        target = connect(target_profile)
    except oracledb.Error:
        source.close()
        raise
    triggers_off = False
    identity_pending: list[tuple[str, str]] = []
    progress = [0]
    try:
        source_cur = source.cursor()
        target_cur = target.cursor()
        source_columns = columns_of(source_cur, table)
        target_columns = columns_of(target_cur, table)
        if not source_columns:
            print(f'正式库没有表 {table}', file=sys.stderr)
            return 1
        if not target_columns:
            print(f'测试库没有表 {table}', file=sys.stderr)
            return 1
        missing = [name for name in target_columns if name not in set(source_columns)]
        if missing:
            print(f'正式库缺少列: {", ".join(missing)}', file=sys.stderr)
            return 1

        source_count = count_rows(source_cur, table)
        target_count = count_rows(target_cur, table)
        print(f'正式库 {source_count} 行，测试库 {target_count} 行')
        if args.limit is not None:
            order = '，按 ID 从大到小' if 'ID' in target_columns else ''
            print(f'本次最多导入 {args.limit} 行{order}')
        if target_count and not args.replace:
            print('测试库这张表已有数据。确认覆盖后加 --replace', file=sys.stderr)
            return 1
        if args.replace and target_count:
            clear_target(target_cur, table)
            target.commit()
            print(f'已清空测试库 {table}')

        identities = identity_columns(target_cur, table)
        sequences = sequence_defaults(target_cur, table)
        disable_triggers(target_cur, table)
        triggers_off = True
        relax_identity(target_cur, table, identities)
        identity_pending = identities
        target.commit()

        copied = copy_rows(
            source_cur,
            target_cur,
            table,
            target_columns,
            args.batch_size,
            progress,
            args.limit,
        )
        if copied:
            restart_identity(target_cur, table, identities)
            restart_sequences(target_cur, table, sequences)
        elif identity_pending:
            restore_identity_mode(target_cur, table, identity_pending)
        identity_pending = []
        target.commit()
        enable_triggers(target_cur, table)
        triggers_off = False
        target.commit()
        print(f'完成: {table} 写入 {copied} 行，测试库现有 {count_rows(target_cur, table)} 行')
        return 0
    except oracledb.Error as exc:
        target.rollback()
        print(exc, file=sys.stderr)
        return 1
    finally:
        cleanup = target.cursor()
        try:
            if identity_pending:
                if progress[0]:
                    restart_identity(cleanup, table, identity_pending)
                else:
                    restore_identity_mode(cleanup, table, identity_pending)
                target.commit()
            if triggers_off:
                enable_triggers(cleanup, table)
                target.commit()
        except oracledb.Error as exc:
            print(f'恢复触发器或身份列失败: {exc}', file=sys.stderr)
        source.close()
        target.close()


if __name__ == '__main__':
    raise SystemExit(main())
