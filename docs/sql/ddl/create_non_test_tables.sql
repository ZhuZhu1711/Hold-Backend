-- PRODUCT_INFO 触发器（源库三个都是 ENABLED）
-- ---------------------------------------------------------------------------
CREATE OR REPLACE TRIGGER TRG_PRODUCT_INFO_LINE_TYPE_ALL
BEFORE INSERT OR UPDATE OF PRODUCT_ID ON PRODUCT_INFO
FOR EACH ROW
BEGIN
    IF :NEW.PRODUCT_ID LIKE '%-3.5%' THEN
        :NEW.LINE_TYPE := 0;
    ELSIF :NEW.PRODUCT_ID LIKE '%-2.6%' THEN
        :NEW.LINE_TYPE := 1;
    ELSE
        :NEW.LINE_TYPE := -1;
    END IF;
END;
/

