-- FT_OWEN 非 _TEST 表结构，供另一台 Oracle 建测试库。
-- 来源：FT_OWEN 数据字典（列、默认值、主键/唯一/外键、索引、注释、触发器、序列）。
--
-- 按 Oracle 11g 编写。11g 没有身份列，也不能把序列.NEXTVAL 写成列默认值，
-- 所以自增 ID 用序列 + BEFORE INSERT 触发器。
--
-- 用法：用目标库的业务用户执行（SQL*Plus / SQLcl / SQL Developer）。
-- DBeaver 不要执行 SET DEFINE OFF；每个触发器只选中 CREATE OR REPLACE TRIGGER
-- 到 END; 再执行，不要带下面单独一行的 /。
-- 对象建在当前用户下，表空间用该用户的默认表空间。
-- 目标用户下这些表、序列和触发器必须还不存在。本脚本不删对象、不导数据。
--
-- 未包含：
--   *_TEST 表及其序列（CIRCULATION_HISTORY_TEST、FT_HOLD_INFO_TEST、
--   FT_HOLD_PREDICT_TEST、FT_HOLD_RECORD_TEST 等）
--   视图 VW_WAFER_YIELD
--   回收站对象
--
-- 序列从各自 MINVALUE 起，不是正式库当前值。
-- 源库 GENERATED ALWAYS 的列：触发器每次插入都写下一个序列值。
-- 源库 GENERATED BY DEFAULT，或默认值是序列.NEXTVAL 的列：只有 ID 为空时才取序列。
-- 显式插入 NULL 时，11g 触发器也会填序列；12c 默认值不会。
-- HOLD_INFO.ID 的身份列原定义是 START WITH 10，对应 SEQ_HOLD_INFO_ID。
-- 源库身份列的系统序列名（ISEQ$$）不会保留。
-- 11g 对象名最长 30 字节，两处超长名称已缩短：
--   FT_HOLD_INFO_HOLD_RECORD_ID_IDX -> FT_HOLD_INFO_HOLD_REC_ID_IDX
--   CIRCULATION_HISTORY_FT_HOLD_RECORD_FK -> CIRC_HIST_HOLD_RECORD_FK
-- TEST_WAFER_UNIQUE 在源库挂在非唯一索引上；这里改成唯一索引，
-- 否则 NOT DEFERRABLE 唯一约束无法复用非唯一索引。
-- SEQ_COM_HOLD、SEQ_FVI_HOLD 没有被这些表引用，一并建上。

SET DEFINE OFF

