-- FT_OWEN.DEFECT_CODE_SYNC_LOG：缺陷代码每日全量同步记录（每个型号一行）
-- debug / release 共用本表。只记日志，不替代 DEFECT_CODE。
-- ID 使用 IDENTITY，不单独建序列。应用启动时 create_all 也会在表不存在时创建。

CREATE TABLE "FT_OWEN"."DEFECT_CODE_SYNC_LOG"
   (	"ID" NUMBER(38,0) GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 NOORDER NOCYCLE NOKEEP NOSCALE NOT NULL ENABLE,
	"RUN_AT" DATE NOT NULL ENABLE,
	"PRODUCT_CODE" VARCHAR2(40 CHAR) NOT NULL ENABLE,
	"PROD_LINE" VARCHAR2(8 CHAR),
	"PRODUCT_INFO_ID" NUMBER(38,0),
	"STATUS" VARCHAR2(16 CHAR) NOT NULL ENABLE,
	"SRC_ROWS" NUMBER(11,0) DEFAULT 0,
	"INSERTED" NUMBER(11,0) DEFAULT 0,
	"UPDATED" NUMBER(11,0) DEFAULT 0,
	"DELETED" NUMBER(11,0) DEFAULT 0,
	"CONFLICTS" NUMBER(11,0) DEFAULT 0,
	"MESSAGE" VARCHAR2(1000 CHAR),
	"STARTED_AT" DATE,
	"FINISHED_AT" DATE,
	 CONSTRAINT "DEFECT_CODE_SYNC_LOG_PK" PRIMARY KEY ("ID")
  USING INDEX TABLESPACE "FT_OWEN" ENABLE
   ) SEGMENT CREATION DEFERRED
  PCTFREE 10 PCTUSED 40 INITRANS 1 MAXTRANS 255
 NOCOMPRESS LOGGING
  TABLESPACE "FT_OWEN";

CREATE INDEX "FT_OWEN"."IDX_DEFECT_SYNC_LOG_RUN"
  ON "FT_OWEN"."DEFECT_CODE_SYNC_LOG" ("RUN_AT", "PRODUCT_CODE")
  TABLESPACE "FT_OWEN";

COMMENT ON TABLE FT_OWEN.DEFECT_CODE_SYNC_LOG IS '缺陷代码每日同步记录。STATUS: OK 成功 / SKIPPED 未建档 / FAILED 失败';
COMMENT ON COLUMN FT_OWEN.DEFECT_CODE_SYNC_LOG.PROD_LINE IS 'FT 或 WLT';
COMMENT ON COLUMN FT_OWEN.DEFECT_CODE_SYNC_LOG.PRODUCT_CODE IS 'PRODUCT_INFO.PRODUCT_ID 型号';
