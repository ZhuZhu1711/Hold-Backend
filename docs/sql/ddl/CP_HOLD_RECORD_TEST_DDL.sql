-- 测试环境：CP_HOLD_RECORD_TEST / CP_CIRCULATION_HISTORY_TEST
-- 不设置 HOLD_ENV 使用本文件中的表；HOLD_ENV=release 用 CP_HOLD_RECORD / CP_CIRCULATION_HISTORY
-- Oracle 11g：自增 ID 用序列 + BEFORE INSERT 触发器，不用身份列。
-- 与 FT_HOLD_RECORD 分开，不写 FT 的流转表。

CREATE SEQUENCE FT_OWEN.CP_HOLD_RECORD_TEST_SEQ
    MINVALUE 1
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE
    NOORDER;

CREATE SEQUENCE FT_OWEN.CP_CIRC_TEST_SEQ
    MINVALUE 1
    START WITH 1
    INCREMENT BY 1
    NOCACHE
    NOCYCLE
    NOORDER;

CREATE TABLE FT_OWEN.CP_HOLD_RECORD_TEST (
    ID NUMBER(38,0) NOT NULL,
    PRODUCT_ID VARCHAR2(20) NOT NULL,
    STATION VARCHAR2(20) NOT NULL,
    EQUIP_ID VARCHAR2(20) NOT NULL,
    LOT_ID VARCHAR2(50) NOT NULL,
    WAFER_ID VARCHAR2(200) NOT NULL,
    HOLD_CODE VARCHAR2(100),
    HOLD_REASON VARCHAR2(512),
    SOURCE NUMBER(38,0) NOT NULL,
    SECOND_CODE VARCHAR2(50),
    ROUTE_ID VARCHAR2(50),
    GRADE_NUM VARCHAR2(512),
    RECORD_TYPE NUMBER(38,0) DEFAULT 0 NOT NULL,
    STATUS NUMBER(38,0) NOT NULL,
    LAST_CIRCULATION_ID NUMBER(38,0),
    HOLD_DTTM DATE,
    CONSTRAINT CP_HOLD_RECORD_TEST_PK PRIMARY KEY (ID)
);

CREATE INDEX FT_OWEN.CP_HOLD_REC_TEST_ST_IDX
    ON FT_OWEN.CP_HOLD_RECORD_TEST (STATUS);

COMMENT ON TABLE FT_OWEN.CP_HOLD_RECORD_TEST IS 'CP Hold 处置单（测试环境），与 FT 分开';
COMMENT ON COLUMN FT_OWEN.CP_HOLD_RECORD_TEST.RECORD_TYPE IS '缺省 0，不是 FT 异常反馈单划分';
COMMENT ON COLUMN FT_OWEN.CP_HOLD_RECORD_TEST.STATUS IS '状态';
COMMENT ON COLUMN FT_OWEN.CP_HOLD_RECORD_TEST.LAST_CIRCULATION_ID IS '最新流转记录的ID';
COMMENT ON COLUMN FT_OWEN.CP_HOLD_RECORD_TEST.SOURCE IS '0: MES 1: JDY';

CREATE TABLE FT_OWEN.CP_CIRCULATION_HISTORY_TEST (
    ID NUMBER(38,0) NOT NULL,
    HOLD_RECORD_ID NUMBER(38,0) NOT NULL,
    DISPOSED_OWNER_ID NUMBER(38,0) DEFAULT 1 NOT NULL,
    DISPOSE NUMBER(38,0) DEFAULT 0,
    NEXT_OWNER_ID NUMBER(38,0),
    DISPOSE_SOURCE VARCHAR2(100),
    DISPOSE_DTTM DATE,
    DISPOSE_TYPE NUMBER(38,0),
    DISPOSE_DETAIL VARCHAR2(4000),
    DISPOSE_NOTE VARCHAR2(1024),
    DISPOSE_MANUAL_NOTE VARCHAR2(1024),
    CONSTRAINT PK_CP_CIRC_TEST PRIMARY KEY (ID)
);

COMMENT ON TABLE FT_OWEN.CP_CIRCULATION_HISTORY_TEST IS 'CP 处置单流转记录（测试环境）';
COMMENT ON COLUMN FT_OWEN.CP_CIRCULATION_HISTORY_TEST.DISPOSED_OWNER_ID IS '默认1(root)代表是系统生成';
COMMENT ON COLUMN FT_OWEN.CP_CIRCULATION_HISTORY_TEST.DISPOSE_SOURCE IS '处置信息来源, SYS or JDY';
COMMENT ON COLUMN FT_OWEN.CP_CIRCULATION_HISTORY_TEST.DISPOSE_TYPE IS '创建、放行、降级、重测、可靠性分析、关闭、转交、回退';

ALTER TABLE FT_OWEN.CP_CIRCULATION_HISTORY_TEST
    ADD CONSTRAINT CP_CIRC_TEST_REC_FK FOREIGN KEY (HOLD_RECORD_ID)
    REFERENCES FT_OWEN.CP_HOLD_RECORD_TEST (ID) ON DELETE CASCADE;

ALTER TABLE FT_OWEN.CP_CIRCULATION_HISTORY_TEST
    ADD CONSTRAINT CP_CIRC_TEST_USERS_FK FOREIGN KEY (DISPOSED_OWNER_ID)
    REFERENCES FT_OWEN.USERS (ID);

CREATE OR REPLACE TRIGGER FT_OWEN.TRG_CP_HOLD_REC_TEST_ID
BEFORE INSERT ON FT_OWEN.CP_HOLD_RECORD_TEST
FOR EACH ROW
BEGIN
    IF :NEW.ID IS NULL THEN
        :NEW.ID := FT_OWEN.CP_HOLD_RECORD_TEST_SEQ.NEXTVAL;
    END IF;
END;
/

CREATE OR REPLACE TRIGGER FT_OWEN.TRG_CP_CIRC_TEST_ID
BEFORE INSERT ON FT_OWEN.CP_CIRCULATION_HISTORY_TEST
FOR EACH ROW
BEGIN
    IF :NEW.ID IS NULL THEN
        :NEW.ID := FT_OWEN.CP_CIRC_TEST_SEQ.NEXTVAL;
    END IF;
END;
/
